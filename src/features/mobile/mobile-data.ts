function dateDaysBefore(anchor: string, days: number): string {
  const date = new Date(`${anchor}T00:00:00Z`);
  date.setUTCDate(date.getUTCDate() - days);
  return date.toISOString().slice(0, 10);
}

function generateAreaTrips(areaId: AreaId, areaIndex: number): FeedTrip[] {
  const areaName = areaMeta[areaId].name;
  const places = placesByArea[areaId];

  return TRIP_THEMES.map((theme, themeIndex) => {
    const used = new Set<string>();
    const picked: MobilePlace[] = [];

    theme.categories.forEach((category, categoryIndex) => {
      const candidates = places.filter((place) => place.category === category && !used.has(place.id));
      if (candidates.length === 0) {
        return;
      }
      const offset = (themeIndex * 7 + categoryIndex * 3 + areaIndex * 5) % candidates.length;
      const place = candidates[offset];
      used.add(place.id);
      picked.push(place);
    });

    const seed = (areaIndex * 31 + themeIndex * 17 + 11) % 97;
    const author = TRIP_AUTHORS[(areaIndex * 4 + themeIndex) % TRIP_AUTHORS.length];

    return {
      id: `seed-${areaId}-${themeIndex}`,
      title: theme.title(areaName),
      description: theme.description,
      authorHandle: author.handle,
      authorName: author.name,
      areaId,
      visibility: "public",
      placeIds: picked.map((place) => place.id),
      likes: 120 + seed * 9,
      comments: 4 + (seed % 23),
      saved: 40 + ((seed * 3) % 180),
      rankScore: 55 + (seed % 40),
      isMine: false,
      publishedAt: dateDaysBefore("2026-08-05", areaIndex * 3 + themeIndex),
    } satisfies FeedTrip;
  });
}

export const seedFeedTrips: FeedTrip[] = (Object.keys(areaMeta) as AreaId[]).flatMap(
  (areaId, areaIndex) => generateAreaTrips(areaId, areaIndex),
);

function haversineKm(a: { lat: number; lng: number }, b: { lat: number; lng: number }): number {
  const R = 6371;
  const dLat = ((b.lat - a.lat) * Math.PI) / 180;
  const dLng = ((b.lng - a.lng) * Math.PI) / 180;
  const lat1 = (a.lat * Math.PI) / 180;
  const lat2 = (b.lat * Math.PI) / 180;
  const h =
    Math.sin(dLat / 2) ** 2 + Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2;

  return 2 * R * Math.asin(Math.sqrt(h));
}

export function nearestAreaId(point: { lat: number; lng: number }): AreaId {
  const areaIds = Object.keys(areaMeta) as AreaId[];
  return areaIds.reduce((closest, candidate) =>
    haversineKm(point, areaMeta[candidate].center) < haversineKm(point, areaMeta[closest].center)
      ? candidate
      : closest,
  );
}

