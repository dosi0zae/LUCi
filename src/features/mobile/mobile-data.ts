function hashString(value: string): number {
  let hash = 0;
  for (let i = 0; i < value.length; i++) {
    hash = (hash * 31 + value.charCodeAt(i)) >>> 0;
  }
  return hash;
}

export function getCafeMenu(place: MobilePlace): MenuItem[] {
  const seed = hashString(place.id);
  const count = 4 + (seed % 3);
  const startIndex = seed % CAFE_MENU_POOL.length;

  return Array.from({ length: count }, (_, i) => {
    const index = (startIndex + i * 7) % CAFE_MENU_POOL.length;
    const base = CAFE_MENU_POOL[index];
    const likeSeed = hashString(`${place.id}:${base.name}`);

    return { ...base, baseLikes: 8 + (likeSeed % 65) };
  });
}
