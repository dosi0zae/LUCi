export function inferArea(prompt: string): AreaId {
  return detectAreaFromText(prompt) ?? "seongsu";
}

// Returns null (instead of defaulting to seongsu) when the text names no area,
// so callers can tell "explicitly mentioned" apart from "ambiguous, guess needed".
export function detectAreaFromText(prompt: string): AreaId | null {
  const text = prompt.replace(/\s/g, "");

  if (/홍대|합정|망원|연남|연희|상수/.test(text)) {
    return "hongdae";
  }

  if (/강남|신논현|역삼|논현|가로수길|신사/.test(text)) {
    return "gangnam";
  }

  if (/성수|건대|서울숲|뚝섬|자양/.test(text)) {
    return "seongsu";
  }

  return null;
}

